#!/usr/bin/env python3
"""Full-resolution masters: the private S3 bucket and the committed manifest.

The bucket (``bridge-visual-masters-<account-id>``, us-east-1, Block Public
Access, versioned, SSE-S3) is the source of truth for the bytes; the work dir
is a local cache of it. The manifest ``scripts/visuals/masters/<id>.json`` is
committed: provenance and acceptance state in git, without the bytes.

Usage:
    masters.py ensure-bucket
    masters.py push <scenario_id>
    masters.py pull <scenario_id>
    masters.py status <scenario_id>

Uses the default AWS credential chain. ``BRIDGE_VISUALS_BUCKET`` overrides the
bucket name.
"""

from __future__ import annotations

import argparse
import json
import mimetypes
import os
from datetime import datetime, timezone
from pathlib import Path

from common import HERE, local_path, sha256_file, work_root

MANIFEST_DIR = HERE / "masters"
REGION = "us-east-1"
# Only these work-dir subtrees are masters; previews and contact sheets are not.
MASTER_DIRS = ("plate", "composites", "layers")


# --- manifest -----------------------------------------------------------------


def manifest_path(scenario_id: str, manifest_dir: Path | None = None) -> Path:
    return (manifest_dir or MANIFEST_DIR) / f"{scenario_id}.json"


def load_manifest(scenario_id: str, manifest_dir: Path | None = None) -> dict:
    path = manifest_path(scenario_id, manifest_dir)
    if path.exists():
        return json.loads(path.read_text())
    return {"scenario_id": scenario_id, "accepted": {}, "objects": {}}


def save_manifest(manifest: dict, manifest_dir: Path | None = None) -> None:
    path = manifest_path(manifest["scenario_id"], manifest_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    manifest["objects"] = dict(sorted(manifest["objects"].items()))
    path.write_text(json.dumps(manifest, indent=2, sort_keys=False) + "\n")


def record(
    scenario_id: str, key: str, meta: dict, manifest_dir: Path | None = None
) -> None:
    """Merge ``meta`` into the manifest entry for ``key`` (an S3 key)."""
    if not key.startswith(f"{scenario_id}/"):
        raise ValueError(f"{key!r} is not under {scenario_id}/")
    manifest = load_manifest(scenario_id, manifest_dir)
    entry = manifest["objects"].get(key, {})
    entry.update(meta)
    entry.setdefault(
        "recorded_at", datetime.now(timezone.utc).isoformat(timespec="seconds")
    )
    manifest["objects"][key] = entry
    save_manifest(manifest, manifest_dir)


def accept(
    scenario_id: str, slot: str, key: str, manifest_dir: Path | None = None
) -> None:
    """Mark ``key`` as the accepted master for ``slot`` (``plate`` / ``level_<n>``)."""
    manifest = load_manifest(scenario_id, manifest_dir)
    if key not in manifest["objects"]:
        raise SystemExit(
            f"{key} is not in the manifest — was it generated by generate.py?"
        )
    manifest["accepted"][slot] = key
    manifest["accepted"] = dict(sorted(manifest["accepted"].items(), key=_slot_order))
    save_manifest(manifest, manifest_dir)


def accepted(
    scenario_id: str, slot: str, manifest_dir: Path | None = None
) -> str | None:
    return load_manifest(scenario_id, manifest_dir)["accepted"].get(slot)


def _slot_order(item: tuple[str, str]) -> tuple[int, int]:
    slot = item[0]
    return (0, 0) if slot == "plate" else (1, int(slot.removeprefix("level_")))


def spend(manifest: dict) -> dict:
    """Total API spend recorded, and the share that went into accepted masters."""
    objects = manifest["objects"]
    total = sum(o.get("cost_usd", 0.0) for o in objects.values())
    kept = sum(
        objects.get(k, {}).get("cost_usd", 0.0) for k in manifest["accepted"].values()
    )
    return {"total_usd": round(total, 4), "accepted_usd": round(kept, 4)}


def describe_file(path: Path) -> dict:
    """The provenance fields every master carries: sha256, pixel size, bytes."""
    from PIL import Image

    with Image.open(path) as img:
        size = list(img.size)
    return {"sha256": sha256_file(path), "size": size, "bytes": path.stat().st_size}


# --- S3 -----------------------------------------------------------------------


def s3_client():
    import boto3

    return boto3.client("s3", region_name=REGION)


def bucket_name(sts=None) -> str:
    if os.environ.get("BRIDGE_VISUALS_BUCKET"):
        return os.environ["BRIDGE_VISUALS_BUCKET"]
    if sts is None:
        import boto3

        sts = boto3.client("sts", region_name=REGION)
    return f"bridge-visual-masters-{sts.get_caller_identity()['Account']}"


def ensure_bucket(s3, bucket: str) -> None:
    """Create (or re-assert) the private, versioned, encrypted masters bucket."""
    try:
        s3.create_bucket(Bucket=bucket)  # us-east-1: no LocationConstraint
    except s3.exceptions.BucketAlreadyOwnedByYou:
        pass
    s3.put_public_access_block(
        Bucket=bucket,
        PublicAccessBlockConfiguration={
            "BlockPublicAcls": True,
            "IgnorePublicAcls": True,
            "BlockPublicPolicy": True,
            "RestrictPublicBuckets": True,
        },
    )
    s3.put_bucket_versioning(
        Bucket=bucket, VersioningConfiguration={"Status": "Enabled"}
    )
    s3.put_bucket_encryption(
        Bucket=bucket,
        ServerSideEncryptionConfiguration={
            "Rules": [
                {"ApplyServerSideEncryptionByDefault": {"SSEAlgorithm": "AES256"}}
            ]
        },
    )


def _local_masters(scenario_id: str, root: Path) -> list[tuple[str, Path]]:
    out = []
    for sub in MASTER_DIRS:
        base = root / scenario_id / sub
        if base.is_dir():
            for p in sorted(base.rglob("*")):
                if p.is_file() and not p.name.startswith("."):
                    out.append((p.relative_to(root).as_posix(), p))
    return out


def _remote_sha(s3, bucket: str, key: str) -> str | None:
    from botocore.exceptions import ClientError

    try:
        head = s3.head_object(Bucket=bucket, Key=key)
    except ClientError as e:
        if e.response["Error"]["Code"] in ("404", "NoSuchKey", "NotFound"):
            return None
        raise
    return head.get("Metadata", {}).get("sha256")


def push(s3, bucket: str, scenario_id: str, root: Path | None = None) -> list[str]:
    """Upload every local master whose bytes S3 doesn't already hold."""
    root = root or work_root()
    sent = []
    for key, path in _local_masters(scenario_id, root):
        sha = sha256_file(path)
        if _remote_sha(s3, bucket, key) == sha:
            continue
        s3.put_object(
            Bucket=bucket,
            Key=key,
            Body=path.read_bytes(),
            ContentType=mimetypes.guess_type(path.name)[0]
            or "application/octet-stream",
            Metadata={"sha256": sha},
        )
        sent.append(key)
    return sent


def pull(
    s3,
    bucket: str,
    scenario_id: str,
    root: Path | None = None,
    manifest_dir: Path | None = None,
) -> list[str]:
    """Download every master under ``<scenario_id>/`` the work dir is missing."""
    root = root or work_root()
    known = load_manifest(scenario_id, manifest_dir)["objects"]
    fetched = []
    token = None
    while True:
        kwargs = {"Bucket": bucket, "Prefix": f"{scenario_id}/"}
        if token:
            kwargs["ContinuationToken"] = token
        page = s3.list_objects_v2(**kwargs)
        for obj in page.get("Contents", []):
            key = obj["Key"]
            dest = root / key
            if dest.exists() and dest.stat().st_size == obj["Size"]:
                want = known.get(key, {}).get("sha256")
                if want is None or want == sha256_file(dest):
                    continue
            body = s3.get_object(Bucket=bucket, Key=key)["Body"].read()
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(body)
            fetched.append(key)
        if not page.get("IsTruncated"):
            return fetched
        token = page["NextContinuationToken"]


# --- CLI ----------------------------------------------------------------------


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("ensure-bucket", help="create/re-assert the private masters bucket")
    for name, helptext in (
        ("push", "upload new local masters to S3"),
        ("pull", "download masters missing from the work dir"),
        ("status", "accepted masters and recorded spend"),
    ):
        p = sub.add_parser(name, help=helptext)
        p.add_argument("scenario_id")
    args = parser.parse_args(argv)

    if args.cmd == "status":
        manifest = load_manifest(args.scenario_id)
        for slot, key in manifest["accepted"].items():
            have = "local" if local_path(key).exists() else "S3 only"
            print(f"{slot:>9}  {key}  ({have})")
        print(json.dumps(spend(manifest)))
        return

    bucket = bucket_name()
    s3 = s3_client()
    if args.cmd == "ensure-bucket":
        ensure_bucket(s3, bucket)
        print(f"s3://{bucket} ready (private, versioned, SSE-S3)")
    elif args.cmd == "push":
        sent = push(s3, bucket, args.scenario_id)
        print(f"pushed {len(sent)} object(s) to s3://{bucket}/{args.scenario_id}/")
    elif args.cmd == "pull":
        got = pull(s3, bucket, args.scenario_id)
        print(f"pulled {len(got)} object(s) into {work_root() / args.scenario_id}")


if __name__ == "__main__":
    main()
